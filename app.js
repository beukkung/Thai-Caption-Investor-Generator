let topic=topics[0],tone=tones[0],platform=platforms[0];

function mountChips(id,items,onSelect){
  const el=document.getElementById(id);
  items.forEach((item,i)=>{
    const b=document.createElement('button');
    b.type='button';b.className='chip'+(i===0?' active':'');b.textContent=item;
    b.onclick=()=>{[...el.children].forEach(x=>x.classList.remove('active'));b.classList.add('active');onSelect(item);};
    el.appendChild(b);
  });
}
mountChips('topics',topics,v=>topic=v);
mountChips('tones',tones,v=>tone=v);
mountChips('platforms',platforms,v=>platform=v);

function adapt(text){
  const context=document.getElementById('context').value.trim();
  let out=context ? context+' — '+text : text;
  if(platform==='IG') out+=' ✨';
  if(platform==='TikTok') out+=' #ชีวิตช่วงนี้';
  if(platform==='Threads' && out.length>105) out=out.split(' — ').pop();
  return out;
}
function pickThree(){
  const pool=[...data[topic][tone]];
  const shuffled=pool.sort(()=>Math.random()-.5);
  return shuffled.slice(0,3).map(adapt);
}
function render(){
  const root=document.getElementById('results');
  root.innerHTML='';
  pickThree().forEach((text,i)=>{
    const card=document.createElement('article');card.className='result-card';
    card.innerHTML='<span class="result-number">OPTION 0'+(i+1)+'</span><div class="result-text"></div><div class="result-actions"><button class="secondary copy-btn">คัดลอก</button><button class="secondary share-btn">แชร์</button></div>';
    card.querySelector('.result-text').textContent=text;
    card.querySelector('.copy-btn').onclick=async()=>{await navigator.clipboard.writeText(text);toast('คัดลอกแล้ว');};
    card.querySelector('.share-btn').onclick=async()=>{if(navigator.share){await navigator.share({text,title:'แคปชั่นไหนดี?'})}else{await navigator.clipboard.writeText(text);toast('คัดลอกไว้ให้แล้ว');}};
    root.appendChild(card);
  });
}
function toast(msg){const t=document.getElementById('toast');t.textContent=msg;t.classList.add('show');setTimeout(()=>t.classList.remove('show'),1300);}
document.getElementById('generate').onclick=render;
document.getElementById('refresh').onclick=render;

